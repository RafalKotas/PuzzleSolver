    public static void printEmptyFieldsAsList(List<List<String>> nonogramBoard) {
        List<String> fieldDeclarations = new ArrayList<>();

        for (int row = 0; row < nonogramBoard.size(); row++) {
            List<String> rowList = nonogramBoard.get(row);
            for (int col = 0; col < rowList.size(); col++) {
                String value = rowList.get(col);
                if ("-".equals(value)) {
                    fieldDeclarations.add("new Field(" + row + ", " + col + ")");
                }
            }
        }

        System.out.println("List<Field> fieldsToCheck = List.of(");
        for (int i = 0; i < fieldDeclarations.size(); i++) {
            System.out.print("    " + fieldDeclarations.get(i));
            if (i < fieldDeclarations.size() - 1) {
                System.out.println(",");
            } else {
                System.out.println();
            }
        }
        System.out.println(");");
    }

    /**
     * Checks if all given fields are empty on nonogramBoard
     *
     * @param nonogramBoard - nonogram board with fields assigned of one of three ("O" - coloured, "X" - finally empty, "-" - not assigned)
     * @return true if all fields are empty, false otherwise
     */
    public static boolean allFieldsEmpty(List<List<String>> nonogramBoard) {
        for (Field field : fieldsToCheck) {
            if (!isFieldEmpty(nonogramBoard, field)) {
                return false;
            }
        }
        return true;
    }
